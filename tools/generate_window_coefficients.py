#!/usr/bin/env python3
"""Generate the synthesizable folded coefficient table for standard windows."""

from __future__ import annotations

import math
from pathlib import Path


SIZES = (8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096)
KINDS = ("hann", "hamming", "blackman")


def coefficient(kind: str, size: int, index: int, periodic: bool) -> int:
    denominator = size if periodic else size - 1
    phase = 2.0 * math.pi * index / denominator
    if kind == "hann":
        value = 0.5 - 0.5 * math.cos(phase)
    elif kind == "hamming":
        value = 0.54 - 0.46 * math.cos(phase)
    else:
        value = 0.42 - 0.5 * math.cos(phase) + 0.08 * math.cos(2.0 * phase)
    return max(0, min(32767, round(value * 32768.0)))


def table_branch(kind: str, periodic: bool) -> list[str]:
    lines = ["            case sample_count is"]
    for size in SIZES:
        last_address = size // 2 if periodic else (size - 1) // 2
        lines.append(f"                when {size} =>")
        lines.append("                    case address is")
        for address in range(last_address + 1):
            value = coefficient(kind, size, address, periodic)
            lines.append(f"                        when {address} => return {value};")
        lines.append("                        when others => return 0;")
        lines.append("                    end case;")
    lines.append("                when others => return 0;")
    lines.append("            end case;")
    return lines


def lookup_function() -> list[str]:
    lines = [
        "    function window_coefficient(kind : integer; periodic : boolean;",
        "        sample_count : positive; address : natural) return integer is",
        "    begin",
        "        case kind is",
    ]
    for kind_index, kind in enumerate(KINDS):
        lines.append(f"            when {kind_index} =>")
        lines.append("                if periodic then")
        lines.extend(table_branch(kind, True))
        lines.append("                else")
        lines.extend(table_branch(kind, False))
        lines.append("                end if;")
    lines.extend(
        [
            "            when others => return 0;",
            "        end case;",
            "    end;",
        ]
    )
    return lines


def generate() -> str:
    prefix = """-- Generated by tools/generate_window_coefficients.py. Do not edit manually.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use work.livt_lang_icontext_package.all;
use work.livt_lang_package.all;

entity livt_signal_window_standardwindowq15pipelineprimitive is
    port (
        ctor_lvt_context_in : in t_icontext_in;
        ctor_shape : in std_logic_vector;
        ctor_kind : in signed(31 downto 0);
        ctor_periodic : in boolean;
        ctor_inputvalid : in boolean;
        ctor_inputready : out boolean;
        ctor_inputsample : in std_logic_vector(15 downto 0);
        ctor_inputfirst : in boolean;
        ctor_inputlast : in boolean;
        ctor_outputvalid : out boolean;
        ctor_outputready : in boolean;
        ctor_outputsample : out std_logic_vector(15 downto 0);
        ctor_outputfirst : out boolean;
        ctor_outputlast : out boolean
    );
end;

architecture rtl of livt_signal_window_standardwindowq15pipelineprimitive is
    function quantize_q15(value : signed(63 downto 0)) return std_logic_vector is
        variable magnitude : unsigned(63 downto 0);
        variable rounded : unsigned(63 downto 0);
        variable sticky : boolean := false;
        variable negative : boolean;
        variable raw : integer;
    begin
        negative := value(63) = '1';
        if negative then magnitude := unsigned(-value);
        else magnitude := unsigned(value); end if;
        rounded := shift_right(magnitude, 15);
        if magnitude(14) = '1' then
            for bit_index in 0 to 13 loop
                if magnitude(bit_index) = '1' then sticky := true; end if;
            end loop;
            if sticky or rounded(0) = '1' then rounded := rounded + 1; end if;
        end if;
        if negative then
            if rounded > to_unsigned(32768, 64) then
                return std_logic_vector(to_signed(-32768, 16));
            end if;
            raw := to_integer(rounded(15 downto 0));
            return std_logic_vector(to_signed(-raw, 16));
        end if;
        if rounded > to_unsigned(32767, 64) then
            return std_logic_vector(to_signed(32767, 16));
        end if;
        return std_logic_vector(to_signed(to_integer(rounded(14 downto 0)), 16));
    end;

    function supported_size(value : positive) return boolean is
    begin
        return value = 8 or value = 16 or value = 32 or value = 64 or
            value = 128 or value = 256 or value = 512 or value = 1024 or
            value = 2048 or value = 4096;
    end;

    function folded_address(sample_count : positive; index : natural;
        periodic : boolean) return natural is
    begin
        if periodic then
            if index > sample_count / 2 then return sample_count - index;
            else return index; end if;
        end if;
        if index > (sample_count - 1) / 2 then return sample_count - 1 - index;
        else return index; end if;
    end;
"""
    suffix = """
    constant SAMPLES : positive := ctor_shape'length;
    signal position : natural range 0 to SAMPLES - 1 := 0;
    signal stage_sample : signed(15 downto 0) := (others => '0');
    signal stage_coefficient : integer range 0 to 32767 := 0;
    signal stage_valid, stage_first, stage_last : std_logic := '0';
    signal result_sample : std_logic_vector(15 downto 0) := (others => '0');
    signal result_valid, result_first, result_last : std_logic := '0';
    signal advance : boolean;
begin
    advance <= result_valid = '0' or ctor_outputready;
    ctor_inputready <= ctor_lvt_context_in.rst = '0' and advance;
    ctor_outputvalid <= ctor_lvt_context_in.rst = '0' and result_valid = '1';
    ctor_outputsample <= result_sample;
    ctor_outputfirst <= result_first = '1';
    ctor_outputlast <= result_last = '1';

    process (ctor_lvt_context_in.clk)
        variable selected_position, address : natural range 0 to SAMPLES - 1;
        variable product : signed(63 downto 0);
    begin
        if rising_edge(ctor_lvt_context_in.clk) then
            if ctor_lvt_context_in.rst = '1' then
                position <= 0;
                stage_valid <= '0';
                stage_first <= '0';
                stage_last <= '0';
                result_valid <= '0';
                result_first <= '0';
                result_last <= '0';
            else
                assert supported_size(SAMPLES)
                    report "standard window length must be a supported power of two in 8..4096" severity failure;
                assert to_integer(ctor_kind) >= 0 and to_integer(ctor_kind) <= 2
                    report "standard window kind must be 0..2" severity failure;
                if advance then
                    result_valid <= stage_valid;
                    result_first <= stage_first;
                    result_last <= stage_last;
                    if stage_valid = '1' then
                        product := resize(stage_sample * stage_coefficient, 64);
                        result_sample <= quantize_q15(product);
                    end if;
                    if ctor_inputvalid then
                        if ctor_inputfirst then selected_position := 0;
                        else selected_position := position; end if;
                        address := folded_address(SAMPLES, selected_position, ctor_periodic);
                        stage_sample <= signed(ctor_inputsample);
                        stage_coefficient <= window_coefficient(to_integer(ctor_kind),
                            ctor_periodic, SAMPLES, address);
                        stage_valid <= '1';
                        if ctor_inputfirst then stage_first <= '1';
                        else stage_first <= '0'; end if;
                        if ctor_inputlast then stage_last <= '1';
                        else stage_last <= '0'; end if;
                        if ctor_inputlast or selected_position = SAMPLES - 1 then
                            position <= 0;
                        else
                            position <= selected_position + 1;
                        end if;
                    else
                        stage_valid <= '0';
                        stage_first <= '0';
                        stage_last <= '0';
                    end if;
                end if;
            end if;
        end if;
    end process;
end;
"""
    return prefix + "\n".join(lookup_function()) + suffix


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    output = root / "src/window/StandardWindowQ15PipelinePrimitive.vhd"
    output.write_text(generate(), encoding="utf-8")
