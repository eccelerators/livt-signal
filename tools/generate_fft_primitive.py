#!/usr/bin/env python3
"""Generate the sequential FFT primitive with a portable Q1.15 twiddle ROM."""

from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "src/transform/SequentialFftQ15Primitive.vhd.in"
OUTPUT = ROOT / "src/transform/SequentialFftQ15Primitive.vhd"
PLACEHOLDER = "        -- GENERATED_TWIDDLE_CASE"
MASTER_SAMPLES = 4096


def q15(value: float) -> int:
    return max(-32768, min(32767, round(value * 32768.0)))


def generate_case() -> str:
    lines: list[str] = []
    for index in range(MASTER_SAMPLES // 2):
        angle = 2.0 * math.pi * index / MASTER_SAMPLES
        real = q15(math.cos(angle))
        imag = q15(-math.sin(angle))
        lines.append(
            f"            when {index} => real_part := {real}; imag_part := {imag};"
        )
    return "\n".join(lines)


def main() -> None:
    template = TEMPLATE.read_text(encoding="utf-8")
    if template.count(PLACEHOLDER) != 1:
        raise RuntimeError("FFT primitive template must contain one twiddle marker")
    generated = template.replace(PLACEHOLDER, generate_case())
    OUTPUT.write_text(
        "-- Generated by tools/generate_fft_primitive.py. Do not edit manually.\n"
        + generated,
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
